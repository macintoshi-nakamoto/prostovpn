"""Ошибка, которую можно показать администратору как есть."""

from __future__ import annotations


class PanelError(Exception):
    """Понятная человеку ошибка бизнес-логики, а не сбой приложения."""

    def __init__(self, message: str, code: str = "") -> None:
        super().__init__(message)
        # Машинный код причины — для тех, кому текст читать нельзя.
        # Приложение переводит вход на свой язык сам: русскую строку панели
        # английскому интерфейсу показывать не годится, а угадывать причину
        # по коду ответа нельзя — 401 приходит и на «пароль не тот», и на
        # «доступ заблокирован».
        self.code = code

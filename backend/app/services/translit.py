"""
Кириллица в латиницу для логинов.

Логин человек набирает в приложении руками, иногда на телефоне с английской
раскладкой, — в нём не должно быть ни кириллицы, ни пробелов.
"""

from __future__ import annotations

_MAP = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e", "ж": "zh",
    "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o",
    "п": "p", "р": "r", "с": "s", "т": "t", "у": "u", "ф": "f", "х": "h", "ц": "c",
    "ч": "ch", "ш": "sh", "щ": "sch", "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu",
    "я": "ya",
    # Украинские и белорусские буквы: контакты приходят разные.
    "і": "i", "ї": "yi", "є": "ye", "ґ": "g", "ў": "u",
}


def slugify(value: str, fallback: str = "user") -> str:
    """
    Латинский слаг из произвольного имени.

    Всё, что не буква и не цифра, схлопывается в один дефис; края
    подчищаются. Пустой результат заменяем на `fallback` — логин без
    осмысленной части всё равно останется уникальным за счёт хвоста.
    """
    out: list[str] = []
    for char in value.lower():
        if char in _MAP:
            out.append(_MAP[char])
        elif char.isascii() and char.isalnum():
            out.append(char)
        else:
            out.append("-")

    slug = "".join(out)
    while "--" in slug:
        slug = slug.replace("--", "-")
    slug = slug.strip("-")
    # Длинные имена режем: логин должен помещаться в поле ввода целиком.
    return slug[:24].strip("-") or fallback

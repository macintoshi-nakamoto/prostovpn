package com.prostovpn.desktop

/**
 * Перебор точек подключения одного узла.
 *
 * Зачем. Узел слушает несколько портов, и какой из них пройдёт — решает не
 * приложение, а сеть человека: канонический 51820 у заметной части операторов
 * режут как известный порт WireGuard. Снаружи это выглядит как исправное
 * приложение, исправный сервер и вечное «подключение».
 *
 * До сих пор этот клиент делал ровно одну попытку на одном порту и при неудаче
 * показывал ошибку — список запасных портов от панели он не читал вовсе.
 *
 * Порядок намеренно последовательный, а не «пробуем всё разом»: у WireGuard
 * попытка означает поднятый интерфейс и переписанную таблицу маршрутизации, и
 * держать три таких сразу нельзя. Зато бюджет на каждого короткий, а
 * сработавший порт запоминается — у человека, в чьей сети проходит только 443,
 * каждое подключение не должно начинаться с потери полуминуты на 51820.
 */
object Endpoints {

    private val ENDPOINT = Regex("""(?im)^(\s*Endpoint\s*=\s*)(\S+?)(?::(\d+))?\s*$""")

    /** Порт из конфига; 0 — строки нет или порт не указан. */
    fun portOf(config: String): Int =
        ENDPOINT.find(config)?.groupValues?.getOrNull(3)?.toIntOrNull() ?: 0

    /**
     * Тот же конфиг, но эндпоинт смотрит в другой порт.
     *
     * Меняем ровно одну строку и ровно её хвост: в конфиге хватает других
     * чисел после «=» и «:» — MTU, junk-параметры, адреса, — и любая менее
     * строгая замена однажды испортит ключ вместо порта. Такая порча не видна
     * глазом: конфиг остаётся верным, а туннель просто не поднимается.
     */
    fun withPort(config: String, port: Int): String =
        ENDPOINT.replace(config) { m -> "${m.groupValues[1]}${m.groupValues[2]}:$port" }

    /**
     * Порядок перебора: сначала запомненный, потом из конфига, потом запасные.
     *
     * Дубликаты выбрасываем: панель намеренно кладёт основной порт в список
     * запасных — клиенту дешевле не ходить дважды в одно место, чем панели
     * гадать, что у него в конфиге.
     */
    fun order(configPort: Int, remembered: Int, alternatives: List<Int>): List<Int> {
        val out = ArrayList<Int>(alternatives.size + 2)
        if (remembered > 0) out.add(remembered)
        if (configPort > 0 && configPort !in out) out.add(configPort)
        for (port in alternatives) if (port > 0 && port !in out) out.add(port)
        return out
    }
}
